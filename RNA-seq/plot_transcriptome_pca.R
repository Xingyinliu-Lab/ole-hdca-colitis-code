library(DESeq2)
library(ggplot2)
a <- commandArgs(trailingOnly=TRUE)
counts <- read.delim(a[1],row.names=1,check.names=FALSE)
meta <- read.delim(a[2],row.names=1,check.names=FALSE)
dds <- DESeqDataSetFromMatrix(round(as.matrix(counts)),meta,~group)
vsd <- vst(dds,blind=TRUE)
d <- plotPCA(vsd,intgroup="group",returnData=TRUE)
p <- ggplot(d,aes(PC1,PC2,colour=group,shape=group))+geom_point()+stat_ellipse()+theme_classic()
ggsave(a[3],p)
